def _build_dsc_section(results):
    """Build DSC results section."""
    if not results:
        return ""

    rows = []
    for r in results:
        label = getattr(r, 'label', 'Sample')
        params = getattr(r, 'parameters', {})
        rows.append(f"""
        <tr>
            <td>{label}</td>
            <td>{params.get('Tg_C', '—')}</td>
            <td>{params.get('Tm_peak_C', '—')}</td>
            <td>{params.get('DHm_Jg', '—')}</td>
            <td><span class="crystallinity-bar" style="width:{params.get('Xc_pct', 0)}px"></span>
                {params.get('Xc_pct', '—')}%</td>
            <td>{params.get('quality_score', '—')}</td>
        </tr>""")

    html = f"""
    <div class="section">
        <h2>DSC — Differential Scanning Calorimetry</h2>
        <table>
            <tr>
                <th>Sample</th><th>Tg (°C)</th><th>Tm (°C)</th>
                <th>ΔHm (J/g)</th><th>Xc</th><th>Quality</th>
            </tr>
            {''.join(rows)}
        </table>
    </div>"""
    return html


