def _build_figures_section(output_dir):
    """Embed figures from output directory as base64."""
    fig_dir = os.path.join(output_dir, 'figures')
    if not os.path.isdir(fig_dir):
        return ""

    figs = sorted([f for f in os.listdir(fig_dir)
                   if f.lower().endswith(('.svg', '.png'))])
    if not figs:
        return ""

    items = []
    for fn in figs[:12]:  # Limit to 12 figures
        fp = os.path.join(fig_dir, fn)
        # For SVG, embed directly; for PNG, base64 encode
        if fn.lower().endswith('.svg'):
            try:
                with open(fp, 'r', encoding='utf-8') as f:
                    svg_content = f.read()
                # Extract just the <svg> tag
                import re
                svg_match = re.search(r'<svg.*?</svg>', svg_content, re.DOTALL)
                if svg_match:
                    items.append(
                        f'<div>{svg_match.group(0)}'
                        f'<div class="caption">{fn}</div></div>')
            except Exception:
                logger.warning("Report SVG figure embedding failed.", exc_info=True)
        else:
            import base64
            try:
                with open(fp, 'rb') as f:
                    b64 = base64.b64encode(f.read()).decode()
                ext = os.path.splitext(fn)[1][1:]
                items.append(
                    f'<div><img src="data:image/{ext};base64,{b64}" />'
                    f'<div class="caption">{fn}</div></div>')
            except Exception:
                logger.warning("Report raster figure embedding failed.", exc_info=True)

    if not items:
        return ""

    return f"""
    <div class="section">
        <h2>Figures</h2>
        <div class="figure-grid">
            {''.join(items)}
        </div>
    </div>"""


def _build_ir_section(results):
    if not results:
        return ""

    rows = []
    temp2d_rows = []
    for r in results:
        label = r.get("label", "Sample") if isinstance(r, dict) else getattr(r, "label", "Sample")
        params = r.get("parameters", {}) if isinstance(r, dict) else getattr(r, "parameters", {})
        analysis_evidence = r.get("analysis_evidence", {}) if isinstance(r, dict) else getattr(r, "analysis_evidence", {})
        if not isinstance(params, dict):
            params = {}
        if not isinstance(analysis_evidence, dict):
            analysis_evidence = {}
        feature = analysis_evidence.get("feature_evidence", {}) if isinstance(analysis_evidence.get("feature_evidence"), dict) else {}
        temp2d = feature.get("temperature_2d_evidence", {}) if isinstance(feature.get("temperature_2d_evidence"), dict) else {}
        if isinstance(temp2d, dict) and temp2d:
            temp2d_rows.append((label, temp2d))
        rows.append(f"""
        <tr>
            <td>{label}</td>
            <td>{params.get('n_peaks', 'N/A')}</td>
            <td>{params.get('Xc_pct', 'N/A')}</td>
            <td>{params.get('n_matches', 'N/A')}</td>
            <td>{params.get('r_squared', 'N/A')}</td>
        </tr>""")

    temp2d_section = ""
    if temp2d_rows:
        temp2d_html_rows = []
        for label, temp2d in temp2d_rows[:8]:
            seq_status = "ready" if float(temp2d.get("sequence_axis_score", 0.0) or 0.0) >= 0.75 else "review"
            status = "paper-ready" if temp2d.get("paper_conclusion_ready") else ("tentative" if temp2d.get("interpretation_ready") else "diagnostic")
            temp2d_html_rows.append(f"""
            <tr>
                <td>{label}</td>
                <td>{seq_status}</td>
                <td>{temp2d.get('matrix_quality_score', 'N/A')}</td>
                <td>{temp2d.get('cos_signal_score', 'N/A')}</td>
                <td>{status}</td>
            </tr>""")
        temp2d_section = f"""
    <div class="section">
        <h2>IR Temperature 2D</h2>
        <table>
            <tr>
                <th>Sample</th><th>Sequence</th><th>Matrix</th>
                <th>Correlation</th><th>Status</th>
            </tr>
            {''.join(temp2d_html_rows)}
        </table>
    </div>"""

    return f"""
    <div class="section">
        <h2>IR - Infrared Spectroscopy</h2>
        <table>
            <tr>
                <th>Sample</th><th>Peaks</th><th>Xc Index</th>
                <th>DFT Matches</th><th>R2</th>
            </tr>
            {''.join(rows)}
        </table>
    </div>{temp2d_section}"""


# ---------------------------------------------------------------------------
#  Main report generator
# ---------------------------------------------------------------------------

def generate_report(project_name="Polymer Analysis",
                    output_dir="",
                    dsc_results=None,
                    waxs_results=None,
                    saxs_results=None,
                    ir_results=None,
                    nmr_results=None,
                    joint_results=None,
                    ) -> str:
    """Generate a complete HTML report.

    Parameters
    ----------
    project_name : str
    output_dir : str
        Directory containing figures/ subfolder.
    *_results : list of result objects
        Results from each technique engine.

    Returns
    -------
    str : Complete HTML report.
    """
    sections = []

    # Technique sections
    if dsc_results:
        sections.append(_build_dsc_section(dsc_results))
    if waxs_results:
        sections.append(_build_waxs_section(waxs_results))
    if saxs_results:
        sections.append(_build_saxs_section(saxs_results))
    if ir_results:
        sections.append(_build_ir_section(ir_results))
    if nmr_results:
        sections.append(_build_nmr_section(nmr_results))

    # Joint analysis
    if joint_results:
        rows = []
        for j in joint_results:
            params = getattr(j, 'parameters', {})
            rows.append(f"""
            <tr>
                <td>{params.get('label', '—')}</td>
                <td>{params.get('Xc_dsc_pct', '—')}%</td>
                <td>{params.get('Xc_waxs_pct', '—')}%</td>
                <td>{params.get('Xc_saxs_pct', '—')}%</td>
                <td><strong>{params.get('Xc_consensus', '—')}%</strong></td>
            </tr>""")
        sections.append(f"""
        <div class="section">
            <h2>Cross-Technique Comparison</h2>
            <table>
                <tr>
                    <th>Sample</th><th>Xc DSC</th><th>Xc WAXS</th>
                    <th>Xc SAXS</th><th>Consensus</th>
                </tr>
                {''.join(rows)}
            </table>
        </div>""")

    # Figures
    if output_dir:
        sections.append(_build_figures_section(output_dir))

    # Technique summary
    techniques = []
    for name, results in [('DSC', dsc_results), ('WAXS', waxs_results),
                            ('SAXS', saxs_results), ('IR', ir_results),
                            ('NMR', nmr_results)]:
        if results:
            techniques.append(name)

    html = REPORT_TEMPLATE.format(
        project_name=project_name,
        timestamp=datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        techniques=', '.join(techniques) if techniques else 'None',
        sections=''.join(sections),
        css=REPORT_CSS,
    )

    return html


def save_report(html, output_dir, filename="polynexus_report.html"):
    """Save HTML report to disk."""
    os.makedirs(output_dir, exist_ok=True)
    path = os.path.join(output_dir, filename)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(html)
    return path
