# ---------------------------------------------------------------------------
#  Symmetry analysis (group theory for IR activity)
# ---------------------------------------------------------------------------

IR_ACTIVE_POINT_GROUPS = {
    # Crystal systems and their IR-active irreducible representations
    "triclinic":    ["Au"],  # C1 or Ci
    "monoclinic":   ["Au", "Bu"],
    "orthorhombic": ["B1u", "B2u", "B3u"],
    "tetragonal":   ["A2u", "Eu"],
    "trigonal":     ["A2u", "Eu"],
    "hexagonal":    ["A2u", "E1u"],
    "cubic":        ["T1u"],
}


def predict_ir_active_modes(space_group_number, n_atoms_per_cell):
    """Predict number of IR-active modes from space group.

    Uses group theory: for a crystal with N atoms per unit cell,
    there are 3N-3 optical modes. The number of IR-active modes
    depends on the point group symmetry.

    Parameters
    ----------
    space_group_number : int
        International space group number (1-230).
    n_atoms_per_cell : int

    Returns
    -------
    dict with {total_modes, ir_active_estimate, point_group_guess}
    """
    total_modes = 3 * n_atoms_per_cell - 3

    # Rough estimates based on space group ranges
    if 1 <= space_group_number <= 2:
        pg = "triclinic"
        n_active = total_modes  # All modes IR-active in C1
    elif 3 <= space_group_number <= 15:
        pg = "monoclinic"
        n_active = total_modes // 2  # Rough
    elif 16 <= space_group_number <= 74:
        pg = "orthorhombic"
        n_active = total_modes // 3
    elif 75 <= space_group_number <= 142:
        pg = "tetragonal"
        n_active = total_modes // 3
    elif 143 <= space_group_number <= 167:
        pg = "trigonal"
        n_active = total_modes // 3
    elif 168 <= space_group_number <= 194:
        pg = "hexagonal"
        n_active = total_modes // 3
    elif 195 <= space_group_number <= 230:
        pg = "cubic"
        n_active = total_modes // 4
    else:
        pg = "unknown"
        n_active = total_modes

    return {
        'total_optical_modes': total_modes,
        'ir_active_estimate': min(n_active, total_modes),
        'point_group': pg,
        'ir_active_representations': IR_ACTIVE_POINT_GROUPS.get(pg, []),
    }


