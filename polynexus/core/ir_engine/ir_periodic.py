"""IR periodic DFT/DFPT interface (IR-D).

Generates input files and parses output for periodic-boundary-condition
IR calculations using:
    - CASTEP (DFPT linear response)
    - VASP (finite differences + Born effective charges)
    - Quantum ESPRESSO (ph.x DFPT)
    - CP2K (vibrational analysis)

For crystalline polymers, periodic DFT properly accounts for:
    - LO-TO splitting at Gamma point
    - Intermolecular coupling in the crystal lattice
    - Correct IR intensities from Born effective charges
"""

from typing import Dict, List, Optional


# ---------------------------------------------------------------------------
#  CASTEP input generator
# ---------------------------------------------------------------------------

def generate_castep_phonon_input(cell_file_content, kpoint_mp=(1,1,1),
                                  functional="PBE",
                                  cutoff_energy_eV=600,
                                  ) -> str:
    """Generate CASTEP .param file for DFPT phonon/IR calculation.

    Requires a .cell file with atomic positions (generated separately).

    Parameters
    ----------
    cell_file_content : str
        Path to or content of the .cell file.
    kpoint_mp : tuple
        Monkhorst-Pack k-point grid.
    functional : str
        'PBE', 'PBEsol', 'LDA', 'PW91', 'WC', 'RPBE'.
    cutoff_energy_eV : float

    Returns
    -------
    str : .param file content
    """
    kpt_str = f"{kpoint_mp[0]} {kpoint_mp[1]} {kpoint_mp[2]}"

    param = f"""# CASTEP DFPT Phonon + IR calculation
# Generated by PolyNexus IR-D module

task = phonon

# Exchange-correlation
xc_functional = {functional}

# Basis set
cut_off_energy = {cutoff_energy_eV} eV

# k-points
kpoint_mp_grid = {kpt_str}

# Phonon calculation
phonon_calculate_ir_intensities = true
phonon_calculate_raman_intensities = false
phonon_fine_method = interpolate
phonon_fine_kpath_spacing = 0.02
phonon_fine_qpath_spacing = 0.02

# Output
write_formatted_dos = true
phonon_write_ eigenvectors = true
write_cell_structure = true

# Convergence
elec_energy_tol = 1e-8 eV/atom
geom_energy_tol = 1e-5 eV/atom
geom_force_tol = 1e-3 eV/A
geom_stress_tol = 0.05 GPa
geom_disp_tol = 1e-3 A

# SCF
max_scf_cycles = 200
mix_history_length = 20
mix_charge_amp = 0.5

# Smearing for metallic systems (not needed for most polymers)
# metals_method = dm
# smearing_width = 0.1 eV
"""
    return param.strip()


# ---------------------------------------------------------------------------
#  VASP INCAR generator for vibrational analysis
# ---------------------------------------------------------------------------

def generate_vasp_vib_incar(encut=500, ediff=1e-7, ismear=0, sigma=0.05,
                             ibrion=5, nfree=2, potim=0.015, nsw=1):
    """Generate VASP INCAR for finite-difference vibrational analysis.

    IBRION=5: compute Hessian by finite differences (no cell relaxation)
    IBRION=6: compute Hessian by finite differences (with symmetry)
    NFREE=2: central differences (more accurate)

    For IR intensities, also compute Born effective charges:
        LEPSILON = .TRUE.
    """
    incar = f"""# VASP Vibrational Analysis INCAR
# Generated by PolyNexus IR-D module

# Electronic
ENCUT = {encut}
EDIFF = {ediff}
PREC = Accurate

# Smearing
ISMEAR = {ismear}
SIGMA = {sigma}

# Vibrational calculation (finite differences)
IBRION = {ibrion}
NFREE = {nfree}
POTIM = {potim}
NSW = {nsw}

# IR intensities via Born effective charges
LEPSILON = .TRUE.

# Output
LREAL = .FALSE.
LORBIT = 11

# Parallelisation
# NCORE = 4
# KPAR = 2
"""
    return incar.strip()


# ---------------------------------------------------------------------------
#  Quantum ESPRESSO ph.x input generator
# ---------------------------------------------------------------------------

def generate_qe_phonon_input(prefix="polymer", outdir="./tmp",
                              alpha_mix=0.7, tr2_ph=1e-12):
    """Generate QE ph.x input for Gamma-point phonon/IR calculation.

    Requires a prior scf calculation with pw.x.
    """
    ph_input = f"""Phonon calculation at Gamma
 &inputph
  prefix = '{prefix}'
  outdir = '{outdir}'
  tr2_ph = {tr2_ph}
  alpha_mix({alpha_mix}) = {alpha_mix}
  ldisp = .false.
  trans = .true.
  asr = .true.
  epsil = .true.       ! Born effective charges for IR
  fildyn = '{prefix}.dyn'
  fildvscf = '{prefix}.dvscf'
 /
0.0 0.0 0.0   ! q-point: Gamma
"""
    return ph_input.strip()


