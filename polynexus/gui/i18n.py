def tr(key: str, *args) -> str:
    """Translate *key* using the currently selected language."""
    return tr_for_language(key, _current_lang, *args)


def tr_for_language(key: str, language: str, *args) -> str:
    """Translate *key* for *language* without changing persisted UI state."""
    language_code = "zh" if str(language or "").strip().lower().startswith("zh") else "en"
    table = _TABLES[language_code]
    text = table.get(key, key)
    return text.format(*args) if args else text


def set_language(lang: str) -> None:
    """Switch the UI language at runtime."""
    global _current_lang
    if lang in _TABLES:
        _current_lang = lang
        _save_lang()


def get_language() -> str:
    """Return the current UI language code."""
    return _current_lang


def get_system_language() -> str:
    """Map the system locale to a supported UI language."""
    try:
        sys_locale = locale.getdefaultlocale()[0]
        if sys_locale:
            sys_lang = sys_locale.lower()[:2]
            if sys_lang in {"zh", "cn", "tw", "hk"}:
                return "zh"
    except (AttributeError, IndexError, TypeError, ValueError):
        logger.warning("Silent exception while detecting system language", exc_info=True)
    return "en"


def _load_lang() -> str:
    """Load the persisted UI language."""
    settings = QSettings("PolyNexus", "PolyNexus")
    saved = settings.value("language", None)
    if saved in _TABLES:
        return saved
    return get_system_language()


def _save_lang() -> None:
    """Persist the current UI language."""
    settings = QSettings("PolyNexus", "PolyNexus")
    settings.setValue("language", _current_lang)


_current_lang = _load_lang()
